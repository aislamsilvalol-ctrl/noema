"""Render benchmarks/README.md from runs.jsonl: the latest run of each model on each dataset.

.venv/bin/python scripts/benchmark_table.py benchmarks/runs > benchmarks/README.md
"""

from __future__ import annotations

import json
import sys
import time
from collections import OrderedDict
from pathlib import Path

NOTES = {
    "half_life": "recall-only model (P(recall | gap)); not a knowledge-tracing predictor, listed for completeness",
    "mastery_heuristic": "the recency rule products ship (close to NOEMA's projection today)",
    "global_mean": "the floor: the base rate",
}


def main(root: str) -> None:
    runs = [json.loads(l) for l in (Path(root) / "runs.jsonl").read_text().splitlines() if l.strip()]
    by_dataset: dict[str, OrderedDict[str, dict]] = {}
    for r in runs:
        key = f"{r['dataset']} ({r['dataset_kind']}, {r['dataset_version']})"
        by_dataset.setdefault(key, OrderedDict())[r["model"]] = r  # latest wins
    print("# Benchmark\n")
    print(
        "Generated by `scripts/benchmark_table.py` from `runs.jsonl`; every row is the latest recorded run of that model on that dataset. Reproduce with:\n"
    )
    print(
        "```bash\n.venv/bin/aquilante benchmark --dataset configs/datasets/synthetic-benchmark.yaml --out benchmarks/runs --seeds 1 --epochs 12\n```\n"
    )
    print(
        "**Read this first.** Synthetic results validate the pipeline, not the models' value for real learners. The simulator is a Rasch-like process with mild log-time forgetting and per-learner rates (see `aquilante/simulation`); a model that wins here has learned that process, nothing more. The table is printed as measured.\n"
    )
    for ds, models in by_dataset.items():
        rows = sorted(models.values(), key=lambda r: -(r["metrics"].get("auc") or 0))
        env = rows[0]["environment"]
        print(f"## {ds}\n")
        print(
            f"Seed {rows[0]['seed']} · {env.get('platform')} · torch {env.get('torch')} · device {env.get('device')} · git {(rows[0].get('git') or '')[:8]} · {time.strftime('%Y-%m-%d', time.localtime(rows[0]['created_at']))}\n"
        )
        print("| model | AUC | log loss | Brier | ECE | accuracy | params | best epoch | train s | note |")
        print("|---|---|---|---|---|---|---|---|---|---|")
        for r in rows:
            m = r["metrics"]
            print(
                f"| {r['model']} | {m['auc']:.4f} | {m['log_loss']:.4f} | {m['brier']:.4f} | {m['ece']:.4f} | {m['accuracy']:.4f} | "
                f"{m.get('parameters', '—')} | {m.get('best_epoch', '—')} | {r['train_seconds']:.1f} | {NOTES.get(r['model'], '')} |"
            )
        base = models.get("global_mean", {}).get("metrics", {})
        if base:
            print(
                f"\nBase rate {base.get('base_rate', float('nan')):.3f}; a constant predictor scores {base.get('accuracy', 0):.3f} accuracy, which is why accuracy is not the headline.\n"
            )


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "benchmarks/runs")
